package ai.xelta.craft.world;

import ai.xelta.craft.XeltaCraftMod;
import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;

import java.util.concurrent.CompletableFuture;
import java.util.concurrent.Executors;
import java.util.concurrent.atomic.AtomicInteger;

/**
 * GeminiWorldBuilder — Places Minecraft blocks from a JSON blueprint
 * generated by {@link ai.xelta.craft.api.GeminiArchitectClient}.
 *
 * Blueprint format (JSON array):
 *   [{"x":0,"y":0,"z":0,"block":"minecraft:stone"}, ...]
 *
 * Coordinates are relative to the player's build origin (feet position).
 * The builder clamps all placements to a safe zone to prevent griefing.
 */
public class GeminiWorldBuilder {

    /** Maximum allowed distance from origin in any axis. Prevents run-away builds. */
    private static final int MAX_SAFE_RADIUS = 50;
    /** Maximum Y height above origin. */
    private static final int MAX_BUILD_HEIGHT = 30;

    /**
     * Parses the JSON blueprint and places blocks in the world asynchronously.
     * Block placement itself happens on the server thread via {@code serverLevel.getServer().execute()}.
     *
     * @param jsonBlueprint  Raw JSON array string from GeminiArchitectClient.
     * @param serverLevel    The server level to build in.
     * @param origin         Build origin (player's feet).
     * @param player         The player who triggered the build (for notifications).
     * @return CompletableFuture<Integer> — number of blocks successfully placed.
     */
    public CompletableFuture<Integer> buildFromBlueprint(
            String jsonBlueprint,
            ServerLevel serverLevel,
            BlockPos origin,
            ServerPlayer player) {

        return CompletableFuture.supplyAsync(() -> {
            // Parse the JSON on a virtual thread
            JsonArray entries = parseBlueprint(jsonBlueprint);
            XeltaCraftMod.LOGGER.info("[GeminiBuilder] Parsed {} block entries from blueprint", entries.size());
            return entries;
        }, Executors.newVirtualThreadPerTaskExecutor())
        .thenCompose(entries -> {
            // Place blocks on the server thread
            CompletableFuture<Integer> result = new CompletableFuture<>();

            serverLevel.getServer().execute(() -> {
                int placed = placeEntries(entries, serverLevel, origin, player);
                result.complete(placed);
            });

            return result;
        });
    }

    // =========================================================
    // Parse JSON Blueprint
    // =========================================================
    private JsonArray parseBlueprint(String jsonBlueprint) {
        try {
            // Attempt to parse. Gemini sometimes still wraps in an outer object.
            JsonElement element = JsonParser.parseString(jsonBlueprint.trim());
            if (element.isJsonArray()) {
                return element.getAsJsonArray();
            }
            // Try to unwrap if it's an object with an array field
            if (element.isJsonObject()) {
                JsonObject obj = element.getAsJsonObject();
                for (String key : new String[]{"blocks", "blueprint", "data", "placements"}) {
                    if (obj.has(key) && obj.get(key).isJsonArray()) {
                        return obj.getAsJsonArray(key);
                    }
                }
            }
            throw new IllegalArgumentException("Gemini blueprint is not a JSON array: "
                + jsonBlueprint.substring(0, Math.min(200, jsonBlueprint.length())));
        } catch (Exception e) {
            XeltaCraftMod.LOGGER.warn("[GeminiBuilder] Failed to parse blueprint: {}", e.getMessage());
            throw new RuntimeException("Blueprint parse failed: " + e.getMessage(), e);
        }
    }

    // =========================================================
    // Place blocks on server thread
    // =========================================================
    private int placeEntries(JsonArray entries, ServerLevel level, BlockPos origin, ServerPlayer player) {
        int placed = 0;
        int skipped = 0;

        for (JsonElement el : entries) {
            if (!el.isJsonObject()) continue;
            JsonObject entry = el.getAsJsonObject();

            try {
                int relX = getInt(entry, "x");
                int relY = getInt(entry, "y");
                int relZ = getInt(entry, "z");
                String blockId = getString(entry, "block");

                // Safety clamp — prevent runaway builds or griefing
                if (Math.abs(relX) > MAX_SAFE_RADIUS
                    || Math.abs(relZ) > MAX_SAFE_RADIUS
                    || relY < -5
                    || relY > MAX_BUILD_HEIGHT) {
                    XeltaCraftMod.LOGGER.debug("[GeminiBuilder] Skipping out-of-bounds entry: x={} y={} z={}", relX, relY, relZ);
                    skipped++;
                    continue;
                }

                BlockState blockState = resolveBlock(blockId);
                BlockPos worldPos = origin.offset(relX, relY, relZ);

                level.setBlock(worldPos, blockState, Block.UPDATE_ALL);
                placed++;

            } catch (Exception e) {
                XeltaCraftMod.LOGGER.debug("[GeminiBuilder] Skipped entry due to error: {}", e.getMessage());
                skipped++;
            }
        }

        XeltaCraftMod.LOGGER.info("[GeminiBuilder] Placed={}, Skipped={}, Origin={}", placed, skipped, origin.toShortString());
        return placed;
    }

    // =========================================================
    // Resolve block ID → BlockState
    // =========================================================
    private BlockState resolveBlock(String blockId) {
        if (blockId == null || blockId.isBlank()) return Blocks.STONE.defaultBlockState();

        // Normalize: ensure namespace prefix
        String normalized = blockId.trim().toLowerCase();
        if (!normalized.contains(":")) {
            normalized = "minecraft:" + normalized;
        }

        try {
            ResourceLocation location = ResourceLocation.parse(normalized);
            Block block = BuiltInRegistries.BLOCK.get(location);

            // BuiltInRegistries returns AIR as a fallback for unrecognised IDs
            if (block == Blocks.AIR && !normalized.equals("minecraft:air")) {
                XeltaCraftMod.LOGGER.debug("[GeminiBuilder] Unknown block '{}', falling back to stone", normalized);
                return Blocks.STONE.defaultBlockState();
            }

            return block.defaultBlockState();
        } catch (Exception e) {
            XeltaCraftMod.LOGGER.debug("[GeminiBuilder] Could not resolve block '{}': {}", normalized, e.getMessage());
            return Blocks.STONE.defaultBlockState();
        }
    }

    // =========================================================
    // JSON helpers
    // =========================================================
    private int getInt(JsonObject obj, String key) {
        if (obj.has(key) && obj.get(key).isJsonPrimitive()) {
            return obj.get(key).getAsInt();
        }
        throw new IllegalArgumentException("Missing integer field: " + key);
    }

    private String getString(JsonObject obj, String key) {
        if (obj.has(key) && obj.get(key).isJsonPrimitive()) {
            return obj.get(key).getAsString();
        }
        throw new IllegalArgumentException("Missing string field: " + key);
    }
}
